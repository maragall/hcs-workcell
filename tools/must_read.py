"""Writes docs/MUST_READ.txt: the code the operator has to read to judge the loop, in the order the plate meets it. Open it with vim:

    python tools/must_read.py && vim docs/MUST_READ.txt        (in vim: /^=== jumps by search; zR opens folds)

Every entry is a whole function or file with its file:line header, taken from the source as it is now, so the list never goes stale.
"""
import ast
import os

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(HERE, "docs", "MUST_READ.txt")

# (why it matters, file, function names or None for the whole file)
ENTRIES = [
    ("1. THE GRIP SIGNAL. How a plate is told from an empty claw: the controller's force-limited close. Everything else is built on this.",
     "devices/clamp.py", None),
    ("2. THE VERDICT on a clamp reading: torque at the limit AND the jaw above the command AND near the width this grip reads on the plate.",
     "perception/predictor.py", ["clamp_holds"]),
    ("3. THE CLAMP AND THE CARRY CHECK as the cycle uses them (teaching mode, the stop when the plate is not in the claw).",
     "procedures/grasp.py", ["_clamp", "_carry_check"]),
    ("4. PICK AND PLACE at the module and the microscope, and the two routes of one plate.",
     "procedures/cycle.py", ["_pick", "_place", "_steps"]),
    ("5. THE HOTEL: slide-in rules, where the carry check sits, the squaring-up before the slide.",
     "procedures/hotel.py", ["_hotel_place", "_hotel_pick", "_square_up", "_hotel_mouth", "_hotel_go_to_approach"]),
    ("6. THE ROUTE STORE: what a stored leg is keyed by (geometry only) and where the planner reads and writes it.",
     "routes/plan.py", ["layout_sig", "plan"]),
    ("7. THE SETUP in the order you run it: sections and their steps.",
     "bringup/sections.py", ["sections", "seat", "grips"]),
    ("8. THE UNATTENDED RUN: what restarts the loop and when it gives up.",
     "tools/keep_running.py", None),
]


def functions(path, names):
    src = open(os.path.join(HERE, path), encoding="utf-8").read()
    lines = src.splitlines()
    out = []
    for node in ast.walk(ast.parse(src)):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name in names:
            out.append((node.lineno, node.end_lineno, "\n".join(lines[node.lineno - 1:node.end_lineno])))
    return sorted(out)


def main():
    parts = ["MUST READ: the code that decides whether the loop works. Generated by tools/must_read.py from the source as it is now.", ""]
    for why, path, names in ENTRIES:
        parts += ["=" * 100, f"=== {why}", "=" * 100, ""]
        if names is None:
            text = open(os.path.join(HERE, path), encoding="utf-8").read().rstrip()
            parts += [f"--- {path} (whole file)", text, ""]
        else:
            for a, b, text in functions(path, names):
                parts += [f"--- {path}:{a}-{b}", text, ""]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8").write("\n".join(parts) + "\n")
    print(f"{OUT}: {len(parts)} lines")


if __name__ == "__main__":
    main()
